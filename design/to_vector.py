"""Turn the mascot SVG from gen.py into Android VectorDrawable XML (and the one-colour PNGs via Chrome).

Usage: python3 -I design/to_vector.py   (writes into app/src/stupify/res and app/src/main/res)
Only the SVG features gen.py uses are handled: circle, ellipse, rect with rx, path, groups with fill,
strokes, opacity and the named gradients.
"""
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # gen.py sits next to this file
import gen  # noqa: E402

APP = os.path.join(HERE, "..", "app", "src")
SVG = "{http://www.w3.org/2000/svg}"

# Gradients in absolute canvas units (the SVG uses per-shape bounding boxes; one shared span looks the same)
GRADIENTS = {
    "afro": ('linear', dict(startX=34.3, startY=18.9, endX=73.7, endY=75.1), gen.AFROS["blue"]),
    "gold": ('linear', dict(startX=54, startY=13, endX=54, endY=34), [("0", "#FFE58A"), ("1", "#F2B233")]),
}


def _num(v):
    return float(v)


def _shape_to_path(el):
    tag = el.tag.replace(SVG, "")
    if tag == "path":
        return el.get("d")
    if tag == "circle":
        cx, cy, r = (_num(el.get(k)) for k in ("cx", "cy", "r"))
        return f"M{cx - r:.2f},{cy:.2f}a{r},{r} 0 1,0 {2 * r:.2f},0a{r},{r} 0 1,0 {-2 * r:.2f},0Z"
    if tag == "ellipse":
        cx, cy, rx, ry = (_num(el.get(k)) for k in ("cx", "cy", "rx", "ry"))
        return f"M{cx - rx:.2f},{cy:.2f}a{rx},{ry} 0 1,0 {2 * rx:.2f},0a{rx},{ry} 0 1,0 {-2 * rx:.2f},0Z"
    if tag == "rect":
        x, y, w, h = (_num(el.get(k)) for k in ("x", "y", "width", "height"))
        r = min(_num(el.get("rx", 0)), w / 2, h / 2)
        return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0 0,1 {r},{r}v{h - 2 * r}a{r},{r} 0 0,1 {-r},{r}"
                f"h{-(w - 2 * r)}a{r},{r} 0 0,1 {-r},{-r}v{-(h - 2 * r)}a{r},{r} 0 0,1 {r},{-r}Z")
    return None


def _color(value, attr):
    """(xml attribute text, child gradient element or '')"""
    m = re.match(r"url\(#(\w+)\)", value or "")
    if not m:
        return f' android:{attr}="{value}"', ""
    kind, coords, stops = GRADIENTS[m.group(1)]
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    xy = " ".join(f'android:{k}="{v}"' for k, v in coords.items())
    return "", (f'<aapt:attr name="android:{attr}"><gradient android:type="{kind}" {xy}>{items}</gradient>'
                f'</aapt:attr>')


def _paths(el, inherited_fill=None, out=None):
    out = [] if out is None else out
    tag = el.tag.replace(SVG, "")
    fill = el.get("fill", inherited_fill)
    if tag in ("svg", "g"):
        for child in el:
            _paths(child, fill, out)
        return out
    d = _shape_to_path(el)
    if not d:
        return out
    attrs, kids = f' android:pathData="{d}"', ""
    if fill and fill != "none":
        a, k = _color(fill, "fillColor")
        attrs, kids = attrs + a, kids + k
    if el.get("stroke"):
        a, k = _color(el.get("stroke"), "strokeColor")
        attrs += a + f' android:strokeWidth="{el.get("stroke-width", "1")}"'
        kids += k
        if el.get("stroke-linecap"):
            attrs += f' android:strokeLineCap="{el.get("stroke-linecap")}"'
        if el.get("stroke-linejoin"):
            attrs += f' android:strokeLineJoin="{el.get("stroke-linejoin")}"'
    if el.get("opacity"):
        attrs += f' android:fillAlpha="{el.get("opacity")}"'
    out.append(f"    <path{attrs}>{kids}</path>" if kids else f"    <path{attrs}/>")
    return out


def vector(svg_text, crop=(0, 0, 108, 108), size_dp=108, comment="", scale=1.0):
    """scale < 1 shrinks the drawing around the mascot's centre (launcher icons show only the middle 66 of 108)."""
    root = ET.fromstring(svg_text)
    x, y, w, h = crop
    body = "\n".join(_paths(root))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by design/to_vector.py from design/gen.py; edit those, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size_dp * w / max(w, h):.0f}dp"
    android:height="{size_dp * h / max(w, h):.0f}dp"
    android:viewportWidth="{w}"
    android:viewportHeight="{h}">
  <group android:translateX="{-x}" android:translateY="{-y}">
  <group android:scaleX="{scale}" android:scaleY="{scale}" android:pivotX="54" android:pivotY="51">
{body}
  </group>
  </group>
</vector>
'''


BACKGROUND = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Stupify launcher icon background: the app's navy with a soft glow behind the mascot. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
  <path android:pathData="M0,0h108v108h-108z">
    <aapt:attr name="android:fillColor">
      <gradient android:type="radial" android:centerX="54" android:centerY="43" android:gradientRadius="76">
        <item android:offset="0" android:color="#16274A"/>
        <item android:offset="1" android:color="#070D1A"/>
      </gradient>
    </aapt:attr>
  </path>
</vector>
'''

LAUNCHER_SCALE = 0.7  # mascot is ~72 units tall; the launcher's safe zone is a 66-unit circle

DENSITIES = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}


def mono_pngs(res, horn):
    tmp = os.path.join(HERE, "build")
    os.makedirs(tmp, exist_ok=True)
    svg_path = os.path.join(tmp, "mono.svg")
    open(svg_path, "w").write(gen.mono(horn, fg="#FFFFFF", scale=LAUNCHER_SCALE))
    for name, px in DENSITIES.items():
        page = os.path.join(tmp, f"mono-{px}.html")
        open(page, "w").write(f'<html><body style="margin:0;background:transparent">'
                              f'<img src="mono.svg" width="{px}" height="{px}" style="display:block"></body></html>')
        out_dir = os.path.join(res, f"drawable-{name}")
        os.makedirs(out_dir, exist_ok=True)
        subprocess.run(["google-chrome", "--headless=new", "--disable-gpu", "--no-sandbox", "--hide-scrollbars",
                        "--default-background-color=00000000", f"--window-size={px},{px}",
                        f"--screenshot={os.path.join(out_dir, 'ic_launcher_monochrome.png')}", f"file://{page}"],
                       check=True, capture_output=True, timeout=60)


if __name__ == "__main__":
    afro, horn = "blue", "classic"  # variant A, chosen 2026-10-24
    mascot = gen.svg(afro, horn, bg=False)
    flavor = os.path.join(APP, "stupify", "res")
    main = os.path.join(APP, "main", "res")
    tight = (22, 12, 64, 78)  # the mascot itself, for logos inside the app
    files = {
        os.path.join(flavor, "drawable", "ic_launcher_foreground.xml"): vector(mascot, comment="Stupify launcher icon foreground (mascot A).", scale=LAUNCHER_SCALE),
        os.path.join(flavor, "drawable", "ic_launcher_background.xml"): BACKGROUND,
        os.path.join(flavor, "drawable", "ic_splash_logo.xml"): vector(mascot, comment="Splash screen and widget placeholder.", scale=LAUNCHER_SCALE),
        os.path.join(flavor, "drawable", "ic_toolbar_tempo.xml"): vector(mascot, tight, 48, "Home header logo (replaces Tempus' record)."),
        os.path.join(main, "drawable", "stupify_logo.xml"): vector(mascot, tight, 96, "Stupify sign-in logo."),
    }
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
    mono_pngs(flavor, horn)
    stale = os.path.join(flavor, "drawable", "ic_launcher_monochrome.xml")
    if os.path.exists(stale):
        os.remove(stale)  # replaced by the per-density PNGs (VectorDrawable has no masks for the cut-outs)
    print("\n".join(os.path.relpath(p, APP) for p in files))
